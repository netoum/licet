defmodule Licet.Migration do
  @moduledoc """
  Creates and drops Licet's tables.

  `mix licet.gen.migration` generates an Ecto migration that calls this module:

      defmodule Licet.Repo.Migrations.InstallLicet do
        use Ecto.Migration

        def up, do: Licet.Migration.up(prefix: "licet")

        def down, do: Licet.Migration.down(prefix: "licet")
      end

  The tables live in their own Postgres schema, named by `:prefix`. The
  statements use `IF NOT EXISTS`, so running `up/1` twice is harmless. In tests,
  `Licet.Testing.migrate!/2` runs the same statements without a migration.
  """

  @prefix ~r/^[a-z_][a-z0-9_]{0,62}$/

  @doc """
  Returns the SQL statements that create the tables in a prefix.

  Takes a prefix string or a keyword list with `:prefix`, which defaults to
  `"licet"`.
  """
  @spec statements(String.t() | keyword()) :: [String.t()]
  def statements(prefix) when is_binary(prefix), do: statements(prefix: prefix)

  def statements(opts) when is_list(opts) do
    prefix = quote_prefix!(Keyword.get(opts, :prefix, "licet"))

    [
      "CREATE SCHEMA IF NOT EXISTS #{prefix}",
      """
      CREATE TABLE IF NOT EXISTS #{prefix}.relationships (
        resource_type text NOT NULL,
        resource_id text NOT NULL,
        relation text NOT NULL,
        subject_type text NOT NULL,
        subject_id text NOT NULL,
        subject_relation text NOT NULL DEFAULT '',
        expires_at timestamptz NULL,
        created_xid xid8 NOT NULL,
        deleted_xid xid8 NULL
      )
      """,
      """
      CREATE UNIQUE INDEX IF NOT EXISTS relationships_living_uidx
      ON #{prefix}.relationships (
        resource_type, resource_id, relation, subject_type, subject_id, subject_relation
      )
      WHERE deleted_xid IS NULL
      """,
      """
      CREATE INDEX IF NOT EXISTS relationships_subject_idx
      ON #{prefix}.relationships (subject_type, subject_id, subject_relation, relation, resource_type)
      WHERE deleted_xid IS NULL
      """,
      """
      CREATE INDEX IF NOT EXISTS relationships_deleted_idx
      ON #{prefix}.relationships (deleted_xid)
      WHERE deleted_xid IS NOT NULL
      """,
      """
      CREATE INDEX IF NOT EXISTS relationships_deleted_resource_idx
      ON #{prefix}.relationships (resource_type, resource_id, relation)
      WHERE deleted_xid IS NOT NULL
      """,
      """
      CREATE INDEX IF NOT EXISTS relationships_deleted_subject_idx
      ON #{prefix}.relationships (subject_type, subject_id, subject_relation, relation, resource_type)
      WHERE deleted_xid IS NOT NULL
      """,
      """
      CREATE TABLE IF NOT EXISTS #{prefix}.transactions (
        xid xid8 PRIMARY KEY,
        snapshot pg_snapshot NOT NULL,
        inserted_at timestamptz NOT NULL DEFAULT clock_timestamp(),
        metadata jsonb NOT NULL DEFAULT '{}'::jsonb
      )
      """,
      """
      CREATE TABLE IF NOT EXISTS #{prefix}.schemas (
        version bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        source text NOT NULL,
        hash text NOT NULL,
        created_xid xid8 NOT NULL,
        deleted_xid xid8 NULL
      )
      """
    ]
  end

  @doc """
  Creates the tables. Call it from an Ecto migration's `up/0`.

  ## Options

    * `:prefix` - the Postgres schema for the tables. Defaults to `"licet"`.
  """
  @spec up(keyword()) :: :ok
  def up(opts \\ []) do
    Enum.each(statements(opts), &Ecto.Migration.execute/1)
  end

  @doc """
  Drops the prefix's Postgres schema and every table in it. Call it from an
  Ecto migration's `down/0`.

  ## Options

    * `:prefix` - the Postgres schema to drop. Defaults to `"licet"`.
  """
  @spec down(keyword()) :: :ok
  def down(opts \\ []) do
    prefix = quote_prefix!(Keyword.get(opts, :prefix, "licet"))
    Ecto.Migration.execute("DROP SCHEMA IF EXISTS #{prefix} CASCADE")
  end

  @doc """
  Returns the source of an Ecto migration module, as written by
  `mix licet.gen.migration`.

  ## Options

    * `:prefix` - the Postgres schema for the tables. Defaults to `"licet"`.
    * `:module` - the migration module name. Defaults to
      `"Licet.Repo.Migrations.InstallLicet"`.
  """
  @spec migration_source(keyword()) :: String.t()
  def migration_source(opts) do
    prefix = quote_prefix!(Keyword.get(opts, :prefix, "licet"))
    module = Keyword.get(opts, :module, "Licet.Repo.Migrations.InstallLicet")

    """
    defmodule #{module} do
      use Ecto.Migration

      def up, do: Licet.Migration.up(prefix: "#{prefix}")

      def down, do: Licet.Migration.down(prefix: "#{prefix}")
    end
    """
  end

  defp quote_prefix!(prefix) do
    if Regex.match?(@prefix, prefix) do
      prefix
    else
      raise Licet.Error.new(
              :invalid_config,
              "prefix #{inspect(prefix)} is not a safe Postgres identifier"
            )
    end
  end
end
